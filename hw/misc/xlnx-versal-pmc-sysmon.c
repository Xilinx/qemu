static void chomp_zero(char *s)
{
    char *p;

    p = s + strlen(s);
    while (p > s) {
        p--;
        switch (p[0]) {
        case '0':
            break;
        case '.':
            p--;  /* fall through to also strip '.' */
        default:
            p[1] = '\0';
            return;
        }
    }

    /* Leave at least 1 untrimmed */
    s[1] = '\0';
}

